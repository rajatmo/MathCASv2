//! Stabiliser chains by the deterministic Schreier-Sims algorithm, in the incremental form of Knuth ("Efficient
//! representation of perm groups", Combinatorica 11, 1991; Seress, *Permutation Group Algorithms*, 4.2): each
//! level keeps its own generators and an explicit transversal; a new generator of level i extends the orbit of the
//! base point b_i, and every Schreier generator u_x s u_(x^s)^-1 met on the way is sifted and, when it does not
//! sift, added to level i + 1. Each pair (orbit point, generator) is processed once, so the result is a base and
//! strong generating set without any randomisation.
use crate::perm::{self, Perm};
use crate::Ctl;
use mc_eval::Res;

/// One level of a stabiliser chain: the base point, the generators added at this level (they fix the earlier base
/// points; with the deeper levels' generators they generate the stabiliser G^(i)), and the orbit of the base point
/// with a transversal `trans[x]` mapping the base point to x.
#[derive(Clone, Debug)]
pub struct Level {
    pub base: u32,
    pub gens: Vec<Perm>,
    pub orbit: Vec<u32>,
    pub trans: Vec<Option<Perm>>,
}

/// A base and strong generating set of a permutation group of degree `n`.
#[derive(Clone, Debug)]
pub struct Chain {
    pub n: usize,
    pub levels: Vec<Level>,
}

impl Level {
    fn new(n: usize, base: u32) -> Level {
        let mut trans = vec![None; n];
        trans[base as usize] = Some(perm::identity(n));
        Level { base, gens: Vec::new(), orbit: vec![base], trans }
    }
}

impl Chain {
    /// The chain of the group generated by `gens` (all of degree `n`), with `prefix` as the first base points.
    pub fn new(n: usize, gens: &[Perm], prefix: &[u32], ctl: &Ctl) -> Res<Chain> {
        let mut c = Chain { n, levels: prefix.iter().map(|&b| Level::new(n, b)).collect() };
        for g in gens {
            c.extend(0, g.clone(), ctl)?;
        }
        Ok(c)
    }

    /// The trivial group of degree n.
    pub fn trivial(n: usize) -> Chain {
        Chain { n, levels: Vec::new() }
    }

    /// Sift `g` from level `from`: the residue and the level where it left the chain (`levels.len()` when it went
    /// through every level).
    pub fn sift_from(&self, from: usize, mut g: Perm) -> (Perm, usize) {
        for i in from..self.levels.len() {
            let l = &self.levels[i];
            let x = g[l.base as usize] as usize;
            match &l.trans[x] {
                Some(u) => g = perm::mul(&g, &perm::inv(u)),
                None => return (g, i),
            }
        }
        let k = self.levels.len();
        (g, k)
    }

    /// Whether `g` (of degree n) is in the group.
    pub fn contains(&self, g: &[u32]) -> bool {
        perm::is_identity(&self.sift_from(0, g.to_vec()).0)
    }

    /// Add `g` (which fixes the first `i` base points) to the stabiliser G^(i).
    pub fn extend(&mut self, i: usize, g: Perm, ctl: &Ctl) -> Res<()> {
        let (res, _) = self.sift_from(i, g.clone());
        if perm::is_identity(&res) {
            return Ok(());
        }
        ctl.step(self.n as u64)?;
        // the original generator (not the residue) is kept: the chain's generators stay readable
        if i == self.levels.len() {
            let b = (0..self.n).find(|&x| g[x] as usize != x).expect("a non-identity permutation moves a point");
            self.levels.push(Level::new(self.n, b as u32));
        }
        self.levels[i].gens.push(g);
        let new = self.levels[i].gens.len() - 1;
        let mut work: Vec<(u32, usize)> = self.levels[i].orbit.iter().map(|&x| (x, new)).collect();
        while let Some((x, si)) = work.pop() {
            let l = &self.levels[i];
            let s = &l.gens[si];
            let y = s[x as usize];
            let ux = l.trans[x as usize].as_ref().expect("orbit points have transversal elements");
            let uxs = perm::mul(ux, s);
            match &l.trans[y as usize] {
                Some(uy) => {
                    let sch = perm::mul(&uxs, &perm::inv(uy));
                    if !perm::is_identity(&sch) {
                        self.extend(i + 1, sch, ctl)?;
                    }
                }
                None => {
                    let l = &mut self.levels[i];
                    l.trans[y as usize] = Some(uxs);
                    l.orbit.push(y);
                    for sj in 0..l.gens.len() {
                        work.push((y, sj));
                    }
                }
            }
        }
        Ok(())
    }

    /// The base points.
    pub fn base(&self) -> Vec<u32> {
        self.levels.iter().map(|l| l.base).collect()
    }

    /// The strong generators (each once).
    pub fn strong_gens(&self) -> Vec<Perm> {
        let mut out: Vec<Perm> = Vec::new();
        for l in &self.levels {
            for g in &l.gens {
                if !out.contains(g) {
                    out.push(g.clone());
                }
            }
        }
        out
    }

    /// Generators of the stabiliser G^(i) of the first i base points.
    pub fn gens_from(&self, i: usize) -> Vec<Perm> {
        let mut out: Vec<Perm> = Vec::new();
        for l in &self.levels[i.min(self.levels.len())..] {
            for g in &l.gens {
                if !out.contains(g) {
                    out.push(g.clone());
                }
            }
        }
        out
    }

    /// The group order, as limbs of a natural number.
    pub fn order(&self) -> Nat {
        let mut o = Nat::one();
        for l in &self.levels {
            o.mul_small(l.orbit.len() as u64);
        }
        o
    }

    /// The group order when it fits in u128.
    pub fn order_u128(&self) -> Option<u128> {
        let mut o: u128 = 1;
        for l in &self.levels {
            o = o.checked_mul(l.orbit.len() as u128)?;
        }
        Some(o)
    }

    /// The order of the stabiliser G^(i).
    pub fn order_from(&self, i: usize) -> Option<u128> {
        let mut o: u128 = 1;
        for l in &self.levels[i.min(self.levels.len())..] {
            o = o.checked_mul(l.orbit.len() as u128)?;
        }
        Some(o)
    }

    /// The elements, in the order of the mixed-radix coordinates (deepest level fastest); `limit` caps the count.
    pub fn elements(&self, limit: usize, ctl: &Ctl) -> Res<Option<Vec<Perm>>> {
        match self.order_u128() {
            Some(o) if o <= limit as u128 => {}
            _ => return Ok(None),
        }
        let mut out = vec![perm::identity(self.n)];
        // g = u_(k-1) ... u_1 u_0: build from the deepest level up
        for l in self.levels.iter().rev() {
            let mut next = Vec::with_capacity(out.len() * l.orbit.len());
            for x in &l.orbit {
                let u = l.trans[*x as usize].as_ref().expect("orbit points have transversal elements");
                for g in &out {
                    next.push(perm::mul(g, u));
                }
                ctl.step(out.len() as u64)?;
            }
            out = next;
        }
        Ok(Some(out))
    }

    /// The index of the element g in [0, |G|) (its mixed-radix coordinates; `None` when g is not in the group).
    /// `pos[i][x]` is the position of x in the orbit of level i.
    pub fn index_of(&self, pos: &[Vec<u32>], mut g: Perm) -> Option<u64> {
        let mut idx: u64 = 0;
        let mut radix: u64 = 1;
        for (i, l) in self.levels.iter().enumerate() {
            let x = g[l.base as usize] as usize;
            let u = l.trans[x].as_ref()?;
            idx += pos[i][x] as u64 * radix;
            radix *= l.orbit.len() as u64;
            g = perm::mul(&g, &perm::inv(u));
        }
        perm::is_identity(&g).then_some(idx)
    }

    /// The orbit positions used by [`Chain::index_of`].
    pub fn positions(&self) -> Vec<Vec<u32>> {
        self.levels
            .iter()
            .map(|l| {
                let mut p = vec![u32::MAX; self.n];
                for (k, &x) in l.orbit.iter().enumerate() {
                    p[x as usize] = k as u32;
                }
                p
            })
            .collect()
    }

    /// A uniformly random element (the product of random transversal elements).
    pub fn random(&self, rng: &mut Rng) -> Perm {
        let mut g = perm::identity(self.n);
        for l in self.levels.iter().rev() {
            let x = l.orbit[rng.below(l.orbit.len() as u64) as usize];
            g = perm::mul(&g, l.trans[x as usize].as_ref().expect("orbit points have transversal elements"));
        }
        g
    }

    /// The canonical representative of the right coset `H g` of this group H: at each level the orbit point whose
    /// image under the current element is least is moved to the base point. Elements of one coset give the same
    /// representative (it is the element of the coset with the least images of the base points, in order).
    pub fn coset_rep(&self, mut g: Perm) -> Perm {
        for l in &self.levels {
            let best = l.orbit.iter().copied().min_by_key(|&x| g[x as usize]).expect("an orbit is not empty");
            let u = l.trans[best as usize].as_ref().expect("orbit points have transversal elements");
            g = perm::mul(u, &g);
        }
        g
    }
}

/// A natural number as 64-bit limbs, least significant first (for group orders past u128).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Nat(pub Vec<u64>);

impl Nat {
    pub fn one() -> Nat {
        Nat(vec![1])
    }

    pub fn mul_small(&mut self, m: u64) {
        let mut carry: u128 = 0;
        for limb in self.0.iter_mut() {
            let v = *limb as u128 * m as u128 + carry;
            *limb = v as u64;
            carry = v >> 64;
        }
        if carry > 0 {
            self.0.push(carry as u64);
        }
    }
}

/// A small deterministic generator (xorshift64*), so that the randomised steps give reproducible results.
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Rng {
        Rng(seed.max(1))
    }

    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    pub fn below(&mut self, m: u64) -> u64 {
        self.next_u64() % m
    }
}
