//! MathCAS v2 further functions: the round 30 coverage library, `mc-cover30` until round 34.
//!
//! Functions whose natural home is another crate, written here so that no other crate changes beyond
//! one-line registrations: most are MathCAS source (`lib/further.mc`, [`SOURCE`]) that calls the other libraries
//! through the evaluator; the machine-number kernels that need speed are natives of this crate ([`julia`]).
//! Methods, literature and decisions: `NOTES.md` (decisions e30.1, e30.2, ...).
#![warn(missing_docs)]
mod foxh;
mod julia;
mod num;

use mc_core::{Heap, Store};
use mc_eval::{Attributes, Kernel};

/// The library's source text.
pub const SOURCE: &str = include_str!("../lib/further.mc");

/// The name of the source in messages.
pub const ORIGIN: &str = "lib/further.mc";

/// The public functions of this crate (natives and source) with a one-line description each.
pub const FUNCTIONS: &[(&str, &str)] = &[
    ("fox_h", "fox_h([[an], [ap]], [[bm], [bq]], z): the Fox H function of the parameter pairs [a_j, A_j], [b_j, B_j]"),
    ("fox_h_reduce", "fox_h_reduce(e, x): e as a combination of inactive Fox H functions of x (for x > 0)"),
    ("meijer_g_reduce", "meijer_g_reduce(e, x): e as a combination of inactive Meijer G functions of x (for x > 0)"),
    ("spheroidal_s1", "spheroidal_s1(n, m, gamma, z): the radial spheroidal function of the first kind S^(m)(1)_n(z, gamma)"),
    ("trig_factor", "trig_factor(e): e factored as a product of trigonometric and hyperbolic functions"),
    ("moment_of_inertia", "moment_of_inertia(reg), (reg, p), (reg, p, v): the inertia tensor of the region about the point p, the moment about the axis through p along v"),
    ("number_field_discriminant", "number_field_discriminant(a): the discriminant of the number field generated by the algebraic number a"),
    ("algebraic_number", "algebraic_number(theta, [c0, c1, ...]): the element c0 + c1 theta + ... of the number field Q(theta), in normal form"),
    ("polynomial_sum_of_squares_list", "polynomial_sum_of_squares_list(p, vars): polynomials q_i with p = sum q_i^2 (for p of degree at most 2)"),
    ("inverse_radon_transform", "inverse_radon_transform(g, [p, phi], [x, y]): the function whose Radon transform is g (Gaussians times polynomials)"),
    ("complete_integral", "complete_integral(eq, u(x, ...), [x, ...]): a complete integral of the first-order partial differential equation"),
    ("julia_set_iteration_count", "julia_set_iteration_count(f, z, z0), (c, z0): the iterations of the rational map f (of z^2 + c) until z0 is caught by an attracting cycle or escapes"),
];

/// Register the natives with `k`.
pub fn install(k: &mut Kernel, h: &Heap) {
    k.register(h.sym("c30_julia_counts"), Attributes::default(), Box::new(julia::JuliaCounts));
    k.register(h.sym("c30_fox_machine"), Attributes::default(), Box::new(foxh::FoxMachine));
}
